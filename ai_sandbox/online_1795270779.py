#!/usr/bin/env python3
"""
Простой демонстрационный скрипт, показывающий принципы
квантовой запутанности через создание и измерение
шумного «Bell‑состояния» двух частиц.
"""

import random
import math

# Представим квантовые состояния переводом в классический
# массив, где 0 = |0⟩, 1 = |1⟩.
# Bell‑состояние (|00⟩ + |11⟩)/√2
# Для простоты будем использовать 50–50 шанс измерить
# совпадающие пары 0‑0 и 1‑1 (отображая протокол "параллельно").

def entangle():
    """
    Возвращает случайный измеренный результат для двух запутанных
    частиц. Идеальное Bell‑состояние гарантирует
    коррелированные измерения: 0–0 или 1–1.
    """
    result = random.choice([(0, 0), (1, 1)])
    return result

def simulate(n=1000):
    """
    Симулирует n измерений распада Bell‑состояния.
    Подсчитывает статистику совпадений и различий.
    """
    corr = 0
    for _ in range(n):
        a, b = entangle()
        if a == b:
            corr += 1
    return corr, n - corr

def fidelity(corr, n):
    """
    Вычисляет простое приближение «достоверности» Bell‑состояния:
    вероятность получить совпадающие результаты.
    """
    return corr / n

# Основная часть, исполняемая сразу при запуске скрипта
if __name__ == "__main__":
    n_trials = 10000
    corr, diff = simulate(n_trials)
    print(f"Измерено {n_trials} пар. "
          f"Совпадение = {corr} ({corr / n_trials:.2%}), "
          f"различие = {diff} ({diff / n_trials:.2%}).")
    print(f"Примерная «достоверность» Bell‑состояния: "
          f"{fidelity(corr, n_trials):.4f}")