import random

def run_agent_debate(topic, xp, elo):
    strategist = random.choice((
        f"Усилить глубину поиска по теме '{topic}' за счёт битовых масок",
        f"Объединить квантовую эвристику '{topic}' с таблицами транспозиций",
        f"Расширить векторную выборку для '{topic}' в 2 раза"
    ))
    critic = random.choice((
        "Риск роста задержки выше 0.08с и перерасхода памяти",
        "Без строгой проверки коллизий возможна деградация точности",
        "Требуется обязательный бенчмарк против текущего чемпиона"
    ))
    arbiter = f"Одобрено с порогом отсечения (XP={xp}, Elo={elo})"
    return f"🗣️ Дебаты агентов: [Стратег: {strategist}] vs [Критик: {critic}] -> [Арбитр: {arbiter}]"
